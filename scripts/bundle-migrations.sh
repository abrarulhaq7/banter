#!/usr/bin/env bash
# Joins migrations into one file to paste into the Supabase SQL editor.
# Use this when the Supabase CLI is not set up.
#
# A new project: every migration.
#   npm run db:bundle
#   then paste supabase/paste-into-sql-editor.sql into Supabase > SQL Editor and press Run.
#
# A project that is already set up: only the migrations from a given one onwards.
#   npm run db:bundle -- 20261125000400
#   then paste supabase/paste-update.sql. Never paste the full file a second time.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FROM="${1:-}"
if [[ -n "$FROM" ]]; then
  OUT="$ROOT/supabase/paste-update.sql"
else
  OUT="$ROOT/supabase/paste-into-sql-editor.sql"
fi

{
  if [[ -n "$FROM" ]]; then
    echo "-- Banter database update. Generated by scripts/bundle-migrations.sh; do not edit."
    echo "-- Paste all of this into the Supabase SQL editor and run it once."
  else
    echo "-- Banter database setup. Generated by scripts/bundle-migrations.sh; do not edit."
    echo "-- Paste all of this into the Supabase SQL editor and run it once on a new project."
  fi
  echo
  echo "begin;"
  for migration in "$ROOT"/supabase/migrations/*.sql; do
    # File names start with a timestamp, so comparing names compares dates.
    if [[ -n "$FROM" && "$(basename "$migration")" < "$FROM" ]]; then
      continue
    fi
    echo
    echo "-- ===================================================================================="
    echo "-- $(basename "$migration")"
    echo "-- ===================================================================================="
    cat "$migration"
  done
  echo
  echo "commit;"
} > "$OUT"

echo "Wrote ${OUT#"$ROOT"/} ($(wc -l < "$OUT" | tr -d ' ') lines)"
